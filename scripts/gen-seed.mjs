// Generates supabase/seed.sql from src/data/catalog.json
// Usage: node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync(new URL("../src/data/catalog.json", import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;

let sql = "-- AURICA BAGS demo seed (generated by scripts/gen-seed.mjs). Safe to re-run.\n\n";

for (const c of data.categories) {
  sql += `insert into public.categories (id,name,slug,description,image_url,sort_order) values (${q(c.id)},${q(c.name)},${q(c.slug)},${q(c.description)},${q(c.image_url)},${c.sort_order}) on conflict (slug) do update set name=excluded.name, description=excluded.description, image_url=excluded.image_url, sort_order=excluded.sort_order;\n`;
}
sql += "\n";
for (const p of data.products) {
  sql += `insert into public.products (id,name,slug,description,category_id,price,compare_at_price,stock,sku,images,colors,occasions,material,dimensions,is_featured,is_new) values (${q(p.id)},${q(p.name)},${q(p.slug)},${q(p.description)},(select id from public.categories where slug=${q(p.category_slug)}),${p.price},${q(p.compare_at_price)},${p.stock},${q(p.sku)},${arr(p.images)},${arr(p.colors)},${arr(p.occasions)},${q(p.material)},${q(p.dimensions)},${p.is_featured},${p.is_new}) on conflict (slug) do nothing;\n`;
}
sql += "\n";
for (const c of data.coupons) {
  sql += `insert into public.coupons (code,description,type,value,min_order,max_discount,usage_limit,is_active) values (${q(c.code)},${q(c.description)},${q(c.type)},${c.value},${c.min_order},${q(c.max_discount)},${q(c.usage_limit)},${c.is_active}) on conflict (code) do nothing;\n`;
}

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("Wrote supabase/seed.sql");
